// Esqueletos de letras y dígitos en sans-serif (estilo Helvetica), para el modo
// tipográfico de G2 (sección I.2, spec §5, G2). Cada glifo es una lista de polilíneas en
// una caja de 60 × 100 (y hacia arriba). Los cruces y las uniones son siempre extremos o
// vértices compartidos de las polilíneas: así `construirEspacio` los identifica.
//
// La clasificación depende de la tipografía: en Helvetica la pierna de la K sale del brazo
// (no del asta), y la cola de la Q atraviesa el óvalo.

const r2 = (v) => Math.round(v * 100) / 100;
const punto = (cx, cy, rx, ry, grados) => {
  const t = (grados * Math.PI) / 180;
  return [r2(cx + rx * Math.cos(t)), r2(cy + ry * Math.sin(t))];
};
/** Arco de elipse de `a0` a `a1` grados (con extremos incluidos). */
const arco = (cx, cy, rx, ry, a0, a1, n = 14) =>
  Array.from({ length: n + 1 }, (_, k) => punto(cx, cy, rx, ry, a0 + ((a1 - a0) * k) / n));

