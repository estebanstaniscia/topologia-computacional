/** Normaliza un texto a los glifos disponibles: mayúsculas, sin tildes (Ñ → N). */
export const glifosDe = (palabra) =>
  [...palabra.normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase()].filter((ch) => ch in GLIFOS);
